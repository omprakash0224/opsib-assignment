"""
AI Investigation Schemas for OPSIB.

Defines the structured input evidence package, the validated AI investigation brief,
and response containers adhering to Task D and ADR-7 (Grounded Citation Guardrails).
"""
from datetime import datetime
from typing import List, Optional
from uuid import UUID
from pydantic import BaseModel, Field


class EvidenceReceiptLine(BaseModel):
    """Normalized evidence for a goods receipt line linked to the purchase order."""
    source_record_id: str
    receipt_number: str
    receipt_line: int
    accepted_qty_base: float
    base_uom: str
    received_at: datetime
    posting_status: str


class EvidencePOLine(BaseModel):
    """Normalized evidence for the purchase order line experiencing the shortfall."""
    source_record_id: str
    po_number: str
    line_number: int
    supplier_code: str
    canonical_product_id: str
    canonical_location_id: str
    ordered_qty_base: float
    base_uom: str
    expected_receipt_by: datetime


class EvidencePackage(BaseModel):
    """
    Grounded context package provided to the AI advisory provider.
    Contains strictly factual, pre-reconciled operational data.
    """
    exception_id: str

    exception_key: str
    po_line: EvidencePOLine
    receipt_lines: List[EvidenceReceiptLine]
    expected_qty_base: float
    received_qty_base: float
    variance_qty_base: float
    base_uom: str
    neutral_summary: str
    missing_evidence: List[str]
    valid_source_record_ids: List[str] = Field(
        description="Whitelist of legitimate source record IDs available in this evidence package"
    )


class InvestigationBrief(BaseModel):
    """
    Structured investigation brief output generated by the AI copilot
    and verified by citation guardrails.
    """
    executive_summary: str = Field(
        description="High-level operational overview of the discrepancy"
    )
    analysis_of_evidence: str = Field(
        description="Detailed review of the supplied PO and Goods Receipt records"
    )
    missing_context: List[str] = Field(
        description="List of unobserved operational facts (e.g., supplier dispatch, ASN, POD)"
    )
    recommended_investigation_steps: List[str] = Field(
        description="Actionable physical and administrative steps for the assigned associate/manager"
    )
    cited_record_ids: List[str] = Field(
        default_factory=list,
        description="Explicit source record IDs cited in this analysis (must be in evidence package)"
    )
    confidence_score: float = Field(
        default=0.9,
        ge=0.0,
        le=1.0,
        description="Self-assessed confidence in the factual grounding of the brief"
    )
    safety_warnings: List[str] = Field(
        default_factory=list,
        description="System-injected warnings for stripped hallucinations or ungrounded citations"
    )
    neutrality_disclaimer: str = Field(
        default="Advisory summary only. Supplier dispatch / ASN data absent; findings do not establish supplier fault or transit loss."
    )


class InvestigationRequest(BaseModel):
    """Optional parameters for the investigation request."""
    use_mock: Optional[bool] = Field(
        default=None,
        description="Explicitly force mock provider (useful for deterministic tests)"
    )
    model_override: Optional[str] = Field(
        default=None,
        description="Optional model override for OpenRouter"
    )


class InvestigationBriefResponse(BaseModel):
    """Full API response wrapper for the investigation brief endpoint."""
    exception_id: str

    exception_key: str
    provider_used: str
    model_used: str
    generated_at: datetime
    brief: InvestigationBrief
